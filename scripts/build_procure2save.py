ROOT = Path(__file__).resolve().parents[1]
ORIGIN = "https://kelechiobijiaku.com"
SIGNATURE = "<!-- Generated by scripts/build_procure2save.py; edit the source files. -->"
ALLOWED_TAGS = set("p h2 h3 h4 h5 strong em b i u span hr br a ul ol li blockquote figure figcaption img sup sub table thead tbody tr th td caption code pre".split())
ALLOWED_ATTRS = set("href title src alt width height id colspan rowspan scope start".split())


def esc(value):
    return html.escape(str(value), quote=True)


class ArticleParser(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.parts, self.paragraphs = [], []
        self.current = None

    def handle_starttag(self, tag, attrs):
        if tag not in ALLOWED_TAGS:
            raise ValueError(f"Unsupported article markup: {tag}")
        for key, value in attrs:
            if key not in ALLOWED_ATTRS:
                raise ValueError(f"Unsupported article attribute: {key}")
            if key in {"href", "src"}:
                parsed = urlparse(value or "")
                if parsed.scheme not in {"", "https", "http", "mailto"} or (value or "").startswith("//"):
                    raise ValueError("Unsafe article link")
                if key == "src" and not (value or "").startswith("/assets/"):
                    raise ValueError("Store article images locally under /assets/")
        if tag == "p":
            self.current = []

    def handle_endtag(self, tag):
        if tag == "p" and self.current is not None:
            paragraph = " ".join("".join(self.current).split())
            if paragraph:
                self.paragraphs.append(paragraph)
            self.current = None

    def handle_data(self, data):
        self.parts.append(data)
        if self.current is not None:
            self.current.append(data)

    @property
    def text(self):
        return " ".join("".join(self.parts).split())


def text_hash(body):
    parser = ArticleParser()
    parser.feed(body)
    return hashlib.sha256(parser.text.encode()).hexdigest()


def local_file(path, prefix=None):
    if not isinstance(path, str) or (prefix and not path.startswith(prefix)):
        raise ValueError(f"Expected a path under {prefix}: {path}")
    resolved = (ROOT / path.lstrip("/")).resolve()
    if not resolved.is_relative_to(ROOT):
        raise ValueError("A source path escapes the repository")
    if not resolved.is_file():
        raise ValueError(f"Missing source file: {path}")
    return resolved


def load_data(path=None, include_approved_drafts=False):
    data = json.loads((path or ROOT / "data/procure2save.json").read_text())
    categories = {c["id"]: c["name"] for c in data["categories"]}
    if len(categories) != len(data["categories"]):
        raise ValueError("Duplicate categories")
    ids, urls, originals = set(), set(), set()
    articles = []
    for source in data["articles"]:
        article = dict(source)
        slug, url = article["id"], article["url"]
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", slug) or slug in ids:
            raise ValueError(f"Invalid or duplicate article ID: {slug}")
        ids.add(slug)
        if not re.fullmatch(r"/(?:[a-z0-9-]+/)+(?:[a-z0-9-]+\.html)?", url) or url == "/procure2save/" or url.startswith("/procure2save/category/") or url in urls:
            raise ValueError(f"Invalid or duplicate permanent article URL: {url}")
        urls.add(url)
        if article.get("linkedinUrl"):
            original = article["linkedinUrl"].rstrip("/")
            parsed = urlparse(original)
            if parsed.scheme != "https" or parsed.hostname not in {"www.linkedin.com", "linkedin.com"} or not parsed.path.startswith("/pulse/"):
                raise ValueError("Use the original published LinkedIn article URL")
            if original in originals:
                raise ValueError("The same LinkedIn edition is already registered")
            originals.add(original)
        if article.get("status") not in {"draft", "published"}:
            raise ValueError(f"Invalid publication status: {slug}")
        if article["status"] == "draft" and (not include_approved_drafts or article.get("approved") is not True):
            continue
        if article.get("approved") is not True:
            raise ValueError(f"Publication requires approved content: {slug}")
        date.fromisoformat(article["date"])
        date.fromisoformat(article.get("modified", article["date"]))
        if not article["categories"] or not set(article["categories"]).issubset(categories):
            raise ValueError(f"Unknown or missing article categories: {slug}")
        body = local_file(article["contentFile"], "content/procure2save/").read_text()
        parser = ArticleParser()
        parser.feed(body)
        if not parser.text or not parser.paragraphs:
            raise ValueError(f"Article body is empty: {slug}")
        cover = local_file(article["coverImage"], "/assets/")
        if not article.get("coverAlt") or min(article.get("coverWidth", 0), article.get("coverHeight", 0)) <= 0:
            raise ValueError(f"Missing cover description or dimensions: {slug}")
        for key, actual in [("textSha256", hashlib.sha256(parser.text.encode()).hexdigest()), ("coverSha256", hashlib.sha256(cover.read_bytes()).hexdigest())]:
            expected = article.get("source", {}).get(key)
            if expected and expected != actual:
                raise ValueError(f"Original {key} changed: {slug}. Verify against the approved source.")
        article.update(body=body, text=parser.text, description=parser.paragraphs[0], minutes=max(1, round(len(parser.text.split()) / 220)))
        articles.append(article)
    articles.sort(key=lambda a: (a["date"], a["id"]), reverse=True)
    return data, articles


def template(name, **values):
    source = (ROOT / "templates/procure2save" / name).read_text()
    return re.sub(r"\{\{([A-Z_]+)\}\}", lambda m: str(values[m[1]]), source)


def pretty_date(value):
    d = date.fromisoformat(value)
    return f"{d.day} {d.strftime('%B %Y')}"


def categories_html(article, data):
    names = {c["id"]: c["name"] for c in data["categories"]}
    return "".join(f'<a href="/procure2save/category/{esc(c)}/">{esc(names[c])}</a>' for c in article["categories"])


def date_html(article):
    return f'<time datetime="{article["date"]}">{pretty_date(article["date"])}</time><span>{article["minutes"]} min read</span>'


def image_html(article, eager=False):
    return f'<img src="{esc(article["coverImage"])}" alt="{esc(article["coverAlt"])}" width="{article["coverWidth"]}" height="{article["coverHeight"]}" loading="{"eager" if eager else "lazy"}" decoding="async"' + (' fetchpriority="high"' if eager else '') + '>'


def card(article, data, featured=False):
    return f'''<article class="p2-card{' p2-feature-card' if featured else ''}">
      <a class="p2-card-image" href="{esc(article['url'])}" tabindex="-1" aria-hidden="true">{image_html(article, featured)}</a>
      <div class="p2-card-copy"><div class="p2-topics">{categories_html(article, data)}</div>
      <h3><a href="{esc(article['url'])}">{esc(article['title'])}</a></h3>
      <div class="p2-meta">{date_html(article)}</div></div></article>'''


