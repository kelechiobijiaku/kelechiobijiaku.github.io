def related_articles(article, articles):
    explicit = article.get('related', [])
    candidates = [a for a in articles if a['id'] != article['id']]
    return sorted(candidates, key=lambda a: (a['id'] in explicit, len(set(a['categories']) & set(article['categories'])), a['date']), reverse=True)[:3]


def article_page(article, articles, data):
    pub = data['publication']
    original = ''
    if article.get('linkedinUrl'):
        if article.get('source', {}).get('platform') == 'LinkedIn':
            original = f'<p class="p2-source">First published on LinkedIn on {pretty_date(article["date"])}. <a href="{esc(article["linkedinUrl"])}" target="_blank" rel="noopener noreferrer">Read the original edition</a>.</p>'
        else:
            original = f'<p class="p2-source">Also published in Procure2save on LinkedIn. <a href="{esc(article["linkedinUrl"])}" target="_blank" rel="noopener noreferrer">Read the LinkedIn edition</a>.</p>'
    body = template('article.html', TITLE=esc(article['title']), TOPICS=categories_html(article,data), DATE=date_html(article), AUTHOR=esc(pub['author']['name']), COVER=image_html(article,True), BODY=article['body'], SOURCE=original, RELATED=''.join(card(a,data) for a in related_articles(article,articles)), SUBSCRIBE=subscription(data), AUTHOR_BOX=author_box(data))
    schema = {"@context":"https://schema.org", "@type":"Article", "@id":ORIGIN+article['url']+'#article', "headline":article['title'], "description":article['description'], "url":ORIGIN+article['url'], "mainEntityOfPage":{"@type":"WebPage", "@id":ORIGIN+article['url']}, "datePublished":article['date'], "dateModified":article.get('modified',article['date']), "author":{"@type":"Person", "@id":ORIGIN+'/#person', "name":pub['author']['name'], "url":pub['author']['url'], "sameAs":pub['author']['linkedinUrl']}, "publisher":{"@type":"Organization", "name":pub['name'], "url":pub['url']}, "image":{"@type":"ImageObject", "url":urljoin(ORIGIN,article['coverImage']), "width":article['coverWidth'], "height":article['coverHeight']}, "articleSection":[c['name'] for c in data['categories'] if c['id'] in article['categories']], "inLanguage":"en", "wordCount":len(article['text'].split()), "articleBody":article['text'], "isPartOf":{"@type":"CreativeWorkSeries", "name":pub['name'], "url":pub['url'], "sameAs":pub['newsletterUrl']}}
    if article.get('linkedinUrl'):
        schema['isBasedOn' if article.get('source', {}).get('platform') == 'LinkedIn' else 'sameAs'] = article['linkedinUrl']
    return shell(article['title']+' | Procure2save',article['description'],article['url'],body,data,article['coverImage'],schema,article)


def write_page(url, content):
    path = ROOT / url.lstrip('/')
    if url.endswith('/'):
        path /= 'index.html'
    if path.exists() and SIGNATURE not in path.read_text():
        raise ValueError(f"Refusing to overwrite an existing unrelated page: {url}")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)


def update_integrations(data, articles):
    pub = data['publication']
    block = f'''<!-- PROCURE2SAVE:START --><aside class="p2-callout"><p class="p2-label">The publication</p><h3><a href="/procure2save/">Procure<span>2</span>save</a></h3><p>Read the latest editions, explore the archive and follow the questions shaping public procurement.</p><div class="p2-actions"><a class="p2-button p2-button-dark" href="/procure2save/">Explore Procure2save</a><a class="p2-text-link" href="{esc(pub['newsletterUrl'])}" target="_blank" rel="noopener noreferrer">Subscribe on LinkedIn</a></div></aside><div data-procure2save-signup></div><!-- PROCURE2SAVE:END -->'''
    for filename in ['index.html','publications.html']:
        path = ROOT / filename
        source = path.read_text()
        if '<!-- PROCURE2SAVE:START -->' in source:
            source = re.sub(r'<!-- PROCURE2SAVE:START -->.*?<!-- PROCURE2SAVE:END -->', lambda _:block, source, flags=re.S)
        else:
            marker = 'The archive includes more than 60 articles and commentaries.</p>'
            if marker not in source:
                raise ValueError(f"Cannot locate the existing writing section: {filename}")
            source = source.replace(marker,marker+block,1)
        for original, slug in [('The Cheapest Bid Can Become the Most Expensive Contract','the-cheapest-bid'),('When Governments Say “Buy Local” — Who Really Wins?','when-governments-say-buy-local')]:
            match = next((a for a in articles if a['id'] == slug),None)
            if match:
                source = source.replace(f'<b>{original}</b>',f'<b><a class="underline" href="{match["url"]}">{original}</a></b>')
        if 'href="/procure2save.css"' not in source:
            source = source.replace('</head>','<link rel="stylesheet" href="/procure2save.css"></head>',1)
        if 'type="application/rss+xml"' not in source:
            source = source.replace('</head>','<link rel="alternate" type="application/rss+xml" title="Procure2save" href="/procure2save/feed.xml"></head>',1)
        if filename == 'publications.html' and '<nav' in source and 'href="/procure2save/">Procure2save</a>' not in source:
            source = source.replace('<a href="research.html">Research</a>','<a href="/procure2save/">Procure2save</a><a href="research.html">Research</a>',1)
        path.write_text(source)


def rss(data, articles):
    pub = data['publication']
    stamp = lambda d: format_datetime(datetime.combine(date.fromisoformat(d), time(), ZoneInfo('Africa/Lagos')))
    items = []
    for a in articles:
        absolute_body = re.sub(r'(href|src)="(/[^\"]*)"',lambda m:f'{m[1]}="{esc(urljoin(ORIGIN,html.unescape(m[2])))}"',a['body'])
        full = f'<p><img src="{urljoin(ORIGIN,a["coverImage"])}" alt="{esc(a["coverAlt"])}"></p>'+absolute_body
        original = f'<link xmlns="http://www.w3.org/2005/Atom" href="{esc(a["linkedinUrl"])}" rel="related"/>' if a.get('linkedinUrl') else ''
        cats = ''.join(f'<category>{esc(c["name"])}</category>' for c in data['categories'] if c['id'] in a['categories'])
        mime = 'image/png' if a['coverImage'].endswith('.png') else 'image/jpeg'
        items.append(f'<item><title>{esc(a["title"])}</title><link>{ORIGIN+a["url"]}</link><guid isPermaLink="true">{ORIGIN+a["url"]}</guid><pubDate>{stamp(a["date"])}</pubDate><dc:creator>{esc(pub["author"]["name"])}</dc:creator><description>{esc(a["description"])}</description><content:encoded>{esc(full)}</content:encoded>{cats}{original}<enclosure url="{urljoin(ORIGIN,a["coverImage"])}" length="{local_file(a["coverImage"]).stat().st_size}" type="{mime}"/></item>')
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom" xmlns:content="http://purl.org/rss/1.0/modules/content/" xmlns:dc="http://purl.org/dc/elements/1.1/"><channel><title>{esc(pub['name'])}</title><link>{pub['url']}</link><description>{esc(pub['description'])}</description><language>en</language><lastBuildDate>{stamp(max([pub['updated']]+[a.get('modified',a['date']) for a in articles]))}</lastBuildDate><copyright>{esc(pub['author']['name'])}</copyright><atom:link href="{pub['url']}feed.xml" rel="self" type="application/rss+xml"/>{''.join(items)}</channel></rss>\n'''


def update_sitemap(urls, updated):
    path = ROOT / 'sitemap.xml'
    source = path.read_text()
    source = re.sub(r'\s*<!-- PROCURE2SAVE:START -->.*?<!-- PROCURE2SAVE:END -->', '', source, flags=re.S)
    existing = {el.text for el in ET.fromstring(source).iter() if el.tag.endswith('}loc')}
    additions = ''.join(f'  <url><loc>{ORIGIN+url}</loc><lastmod>{updated}</lastmod></url>\n' for url in urls if ORIGIN+url not in existing)
    block = '  <!-- PROCURE2SAVE:START -->\n'+additions+'  <!-- PROCURE2SAVE:END -->\n'
    path.write_text(source.replace('</urlset>',block+'</urlset>'))


def build():
    data, articles = load_data()
    pub = data['publication']
    if not articles:
        raise ValueError('At least one approved article is needed for the publication hub')
    counts = Counter(c for a in articles for c in a['categories'])
    topics = ''.join(f'<a class="p2-topic-link" href="/procure2save/category/{c["id"]}/">{esc(c["name"])} <span>{counts[c["id"]]}</span></a>' for c in data['categories'])
    features = [a for a in articles if a.get('featured')][:2] or articles[:1]
    latest = [a for a in articles if a not in features][:3]
    body = template('hub.html', TAGLINE=esc(pub['tagline']), DESCRIPTION=esc(pub['description']), NEWSLETTER=esc(pub['newsletterUrl']), FEATURED=''.join(card(a,data,True) for a in features), LATEST=''.join(card(a,data) for a in latest), TOPICS=topics, ARCHIVE=archive(articles,data), AUTHOR_BOX=author_box(data), SUBSCRIBE=subscription(data))
    write_page('/procure2save/',shell('Procure2save | Public procurement, law & governance',pub['description'],'/procure2save/',body,data,articles[0]['coverImage']))
    urls = ['/procure2save/']
    for a in articles:
        write_page(a['url'],article_page(a,articles,data))
        urls.append(a['url'])
    for category in data['categories']:
        selected = [a for a in articles if category['id'] in a['categories']]
        url = '/procure2save/category/'+category['id']+'/'
        cards = ''.join(card(a,data) for a in selected) or '<p>New editions on this topic will appear here.</p>'
        body = template('category.html', NAME=esc(category['name']), COUNT=str(len(selected)), CARDS=cards, SUBSCRIBE=subscription(data))
        write_page(url,shell(category['name']+' | Procure2save','Procure2save articles on '+category['name'].lower()+', by '+pub['author']['name']+'.',url,body,data,selected[0]['coverImage'] if selected else None))
        urls.append(url)
    (ROOT/'procure2save/feed.xml').write_text(rss(data,articles))
    index = [{key:a[key] for key in ['id','url','title','date','categories','text']} for a in articles]
    # A static JSON index keeps full-text search local to the visitor's browser.
    (ROOT/'data/procure2save-search.json').write_text(json.dumps(index,ensure_ascii=False,separators=(',',':'))+'\n')
    update_integrations(data,articles)
    update_sitemap(urls,max([pub['updated']]+[a.get('websitePublished',a['date']) for a in articles]))
    print(f'Built Procure2save: {len(articles)} complete articles, {len(data["categories"])} topics, full-text search, RSS and sitemap.')


if __name__ == '__main__':
    build()
